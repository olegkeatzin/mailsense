import { canOpenPeriod, canReopenPeriod, reopenablePeriods, type PeriodState } from "./numbering.js";

/**
 * Отмена закрытия года: когда она безопасна.
 *
 * Правило заказчика (и Lead): переоткрыть год можно РОВНО пока в новом году нет
 * ни одного документа — номера ещё не выдавались, столкнуться нечему. Как только
 * первый документ нового года зарегистрирован, отмена запрещена и текст объясняет,
 * ПОЧЕМУ, а не просто «нельзя».
 */
const state = (openPeriod: string | null, archivedPeriods: string[]): PeriodState => ({
  openPeriod,
  archivedPeriods
});

describe("закрытый год не принимает документы", () => {
  test("самый поздний год журнала, но уже выгруженный — регистрация запрещена", () => {
    // ⚠️ Реальная дыра: после выгрузки 2026 самый поздний год журнала всё ещё 2026,
    // и ворота пускали в него документы — они не попадали в уже снятый архив.
    const gate = canOpenPeriod("2026", state("2026", ["2026"]));
    expect(gate.ok).toBe(false);
    // Отказ обязан подсказывать выход, а не просто «нельзя».
    expect(gate.reason).toContain("отмените закрытие");
  });

  test("новый год после выгрузки предыдущего — по-прежнему можно", () => {
    expect(canOpenPeriod("2027", state("2026", ["2026"]))).toEqual({ ok: true });
  });

  test("обычный текущий год без архива — можно", () => {
    expect(canOpenPeriod("2026", state("2026", []))).toEqual({ ok: true });
  });
});

describe("можно ли переоткрыть год", () => {
  test("архивный год, в новом году пусто — можно", () => {
    // 2026 закрыт, документов 2027 нет: openPeriod всё ещё 2026 (это максимум reg_period).
    expect(canReopenPeriod("2026", state("2026", ["2026"]))).toEqual({ ok: true });
  });

  test("год не закрыт — отменять нечего, и это сказано прямо", () => {
    const res = canReopenPeriod("2026", state("2026", []));
    expect(res.ok).toBe(false);
    expect(res.reason).toContain("не закрыт");
  });

  test("в новом году уже есть документы — отказ с объяснением, в каком году", () => {
    const res = canReopenPeriod("2026", state("2027", ["2026"]));
    expect(res.ok).toBe(false);
    // ⚠️ Причина обязана называть год: «нельзя» без объяснения человек проверить не может.
    expect(res.reason).toContain("2027");
    expect(res.reason).toContain("документ");
  });

  test("документы в году ПОСЛЕ закрытого тоже мешают, даже если между ними пропуск", () => {
    const res = canReopenPeriod("2026", state("2028", ["2026"]));
    expect(res.ok).toBe(false);
    expect(res.reason).toContain("2028");
  });

  test("документы внутри самого переоткрываемого года не мешают", () => {
    // В закрытом году документы есть по определению — именно их и выгружали.
    expect(canReopenPeriod("2026", state("2026", ["2026", "2025"]))).toEqual({ ok: true });
  });

  test("пустой журнал: переоткрывать нечего", () => {
    const res = canReopenPeriod("2026", state(null, []));
    expect(res.ok).toBe(false);
  });
});

describe("какие годы можно переоткрыть", () => {
  test("из архива берём только те, за которыми нет документов", () => {
    expect(reopenablePeriods(state("2026", ["2025", "2026"]))).toEqual(["2026"]);
  });

  test("после первого документа нового года список пуст", () => {
    expect(reopenablePeriods(state("2027", ["2025", "2026"]))).toEqual([]);
  });

  test("годы ДО последнего документа не отменяются: позже них номера уже выданы", () => {
    // 2026 — самый поздний год с документами, поэтому отменить можно только 2026:
    // закрытие 2024 или 2025 откатило бы нумерацию, которая уже продолжилась.
    expect(reopenablePeriods(state("2026", ["2024", "2025", "2026"]))).toEqual(["2026"]);
  });
});
