/**
 * Владелец настроек каталога (LDAP).
 *
 * По умолчанию настройки лежат в локальной SQLite — это режим автономного
 * почтового клиента, где сервера нет вообще.
 *
 * Когда рядом работает серверная часть, владельцем становится она: адрес каталога,
 * Base DN и форматы логина задаёт предприятие, а от пользователя требуется только
 * ввести свой логин и пароль. Иначе каждый мог бы указать произвольный каталог и
 * подменить адресную книгу (а в пределе — и подсунуть чужие адреса в автодополнение).
 *
 * Core про docflow не знает: он объявляет интерфейс, а реализацию регистрирует
 * владелец хранилища при старте. Зависимость остаётся односторонней.
 */
export interface LdapSettingsStore {
  /**
   * Синхронное чтение: настройки нужны в горячих путях (адресная книга, вход),
   * поэтому реализация обязана держать значения в памяти.
   */
  read(): Record<string, string> | null;
  /** Запись. Хранилище может быть удалённым, отсюда асинхронность. */
  write(values: Record<string, string>): Promise<void>;
}

let external: LdapSettingsStore | null = null;

/** Регистрирует внешнее хранилище. null — вернуться к локальной SQLite. */
export function setLdapSettingsStore(store: LdapSettingsStore | null): void {
  external = store;
}

export function ldapSettingsStore(): LdapSettingsStore | null {
  return external;
}
